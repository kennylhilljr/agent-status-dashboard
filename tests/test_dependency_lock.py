"""Checks that requirements.in and the hashed requirements.txt lock stay consistent."""

import re
from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

REPO_ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS_IN = REPO_ROOT / "requirements.in"
REQUIREMENTS_TXT = REPO_ROOT / "requirements.txt"

# Tools CI needs from the lock; the workflow installs nothing else.
REQUIRED_TOOLS = {"pytest", "pytest-asyncio", "pytest-cov", "playwright", "pyyaml", "ruff"}


def _input_requirements() -> list[Requirement]:
    requirements = []
    for raw in REQUIREMENTS_IN.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            requirements.append(Requirement(line))
    return requirements


def _locked_sources() -> dict[str, set[str]]:
    """Parse pip-compile's "# via" annotations into {package: {sources}}.

    A source is either another normalized package name or "-r requirements.in".
    """
    sources: dict[str, set[str]] = {}
    current = None
    in_via = False
    for raw in REQUIREMENTS_TXT.read_text().splitlines():
        match = re.match(r"([A-Za-z0-9._-]+)==", raw)
        if match:
            current = canonicalize_name(match.group(1))
            sources[current] = set()
            in_via = False
            continue
        comment = raw.strip().removeprefix("#").strip()
        if current is None or not raw.lstrip().startswith("#"):
            continue
        if comment.startswith("via"):
            in_via = True
            comment = comment.removeprefix("via").strip()
        if in_via and comment:
            if comment.startswith("-r "):
                sources[current].add("-r requirements.in")
            else:
                sources[current].add(canonicalize_name(comment))
    return sources


def _locked_entries() -> dict[str, tuple[str, list[str]]]:
    """Parse requirements.txt into {normalized name: (version, hashes)}."""
    entries: dict[str, tuple[str, list[str]]] = {}
    text = REQUIREMENTS_TXT.read_text().replace("\\\n", " ")
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        spec, *options = line.split()
        match = re.fullmatch(r"([A-Za-z0-9._-]+)==([^\s;]+)", spec)
        assert match, f"requirements.txt entry is not an exact pin: {spec!r}"
        hashes = [opt.removeprefix("--hash=") for opt in options if opt.startswith("--hash=")]
        entries[canonicalize_name(match.group(1))] = (match.group(2), hashes)
    return entries


def test_input_names_are_unique():
    names = [canonicalize_name(req.name) for req in _input_requirements()]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    assert duplicates == []


def test_input_declares_required_test_tools():
    names = {canonicalize_name(req.name) for req in _input_requirements()}
    assert REQUIRED_TOOLS <= names


def test_lock_header_records_regeneration_command():
    header = REQUIREMENTS_TXT.read_text().split("\n\n", 1)[0]
    assert "autogenerated by pip-compile with Python 3.11" in header
    assert "--generate-hashes" in header
    assert "requirements.in" in header


def test_every_locked_package_is_pinned_with_hashes():
    entries = _locked_entries()
    assert entries, "requirements.txt has no entries"
    unhashed = sorted(name for name, (_, hashes) in entries.items() if not hashes)
    assert unhashed == []
    for name, (_, hashes) in entries.items():
        for digest in hashes:
            assert re.fullmatch(r"sha256:[0-9a-f]{64}", digest), (name, digest)


def test_lock_satisfies_every_input():
    entries = _locked_entries()
    for req in _input_requirements():
        name = canonicalize_name(req.name)
        assert name in entries, f"{req.name} is missing from requirements.txt"
        version, _ = entries[name]
        assert req.specifier.contains(version, prereleases=True), (str(req), version)


def test_lock_contains_only_what_inputs_require():
    """Every locked package must be declared or needed by a declared package."""
    sources = _locked_sources()
    assert set(sources) == set(_locked_entries())
    declared = {canonicalize_name(req.name) for req in _input_requirements()}
    reachable = set(declared)
    changed = True
    while changed:
        changed = False
        for name, via in sources.items():
            if name not in reachable and via & reachable:
                reachable.add(name)
                changed = True
    for name in declared:
        assert "-r requirements.in" in sources.get(name, set()), name
    assert sorted(set(sources) - reachable) == []


def test_installed_distributions_match_lock():
    mismatched = []
    for name, (version, _) in _locked_entries().items():
        try:
            installed = metadata.version(name)
        except metadata.PackageNotFoundError:
            mismatched.append(f"{name}: not installed (lock has {version})")
            continue
        if installed != version:
            mismatched.append(f"{name}: installed {installed}, lock has {version}")
    assert mismatched == []
